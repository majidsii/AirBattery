function vectorAsset(src: string): DeviceArtworkAsset {
  return { src, sourceKind: 'vector-fallback', mirrorSafe: true };
}

function exactAsset(
  src: string,
  mirrorSafe = false,
): DeviceArtworkAsset {
  return { src, sourceKind: 'exact-photo', mirrorSafe };
}

export function mergeAssetSets(
  artworkKey: string,
  fallback: VectorArtworkAssetSet,
): DeviceArtworkAssetSet {
  const exact = exactArtworkAssets[artworkKey];
  return {
    single: exact?.single
      ? exactAsset(exact.single.src, exact.single.mirrorSafe)
      : vectorAsset(fallback.single),
    pair: exact?.pair
      ? exactAsset(exact.pair.src, exact.pair.mirrorSafe)
      : vectorAsset(fallback.pair),
    case: exact?.case
      ? exactAsset(exact.case.src, exact.case.mirrorSafe)
      : vectorAsset(fallback.case),
  };
}

export function resolveArtworkAssetSet(artworkKey: string): DeviceArtworkAssetSet | null {
  const normalizedKey = artworkKey.toLowerCase();
  const family = artworkAliases[normalizedKey];
  const fallback = family ? familyAssets[family] : undefined;
  return fallback ? mergeAssetSets(normalizedKey, fallback) : null;
}

